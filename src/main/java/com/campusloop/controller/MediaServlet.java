package com.campusloop.controller;

import com.campusloop.config.AppConfig;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import javax.servlet.annotation.WebServlet;
import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;

/**
 * GET /media/{listings|profiles}/{32-hex}.{jpg|png|webp}
 *
 * Streams uploaded images from the upload directory (outside the webapp, so they
 * survive redeploys). Only names generated by ImageStorage are accepted, and the
 * resolved path is re-checked to be inside the upload directory, so path
 * traversal ("../") is impossible.
 */
@WebServlet(name = "MediaServlet", urlPatterns = "/media/*")
public class MediaServlet extends HttpServlet {

    private static final long serialVersionUID = 1L;
    private static final Pattern SAFE_PATH =
            Pattern.compile("^/(listings|profiles)/([a-f0-9]{32})\\.(jpg|png|webp)$");

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp) throws IOException {
        String info = req.getPathInfo();
        Matcher m = info == null ? null : SAFE_PATH.matcher(info);
        if (m == null || !m.matches()) {
            resp.sendError(HttpServletResponse.SC_NOT_FOUND);
            return;
        }
        Path root = AppConfig.get().getUploadDir();
        Path file = root.resolve(m.group(1)).resolve(m.group(2) + "." + m.group(3)).normalize();
        if (!file.startsWith(root) || !Files.isRegularFile(file)) {
            resp.sendError(HttpServletResponse.SC_NOT_FOUND);
            return;
        }

        String ext = m.group(3);
        String type = "jpg".equals(ext) ? "image/jpeg" : "png".equals(ext) ? "image/png" : "image/webp";
        resp.setContentType(type);
        resp.setContentLengthLong(Files.size(file));
        // File names are random and never reused, so the content never changes.
        resp.setHeader("Cache-Control", "public, max-age=31536000, immutable");
        resp.setHeader("Content-Disposition", "inline");
        try (InputStream in = Files.newInputStream(file); OutputStream out = resp.getOutputStream()) {
            byte[] buffer = new byte[16 * 1024];
            int n;
            while ((n = in.read(buffer)) != -1) {
                out.write(buffer, 0, n);
            }
        }
    }
}
